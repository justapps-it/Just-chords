// Packs dist/ into a module so the Worker can serve the app without the
// Workers Assets upload (used by `npm run deploy:bundle`, e.g. from
// environments whose proxy rewrites the Authorization header).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const root = new URL('../dist/', import.meta.url).pathname;
const TYPES = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.json': 'application/json', '.webmanifest': 'application/manifest+json', '.wasm': 'application/wasm',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.ico': 'image/x-icon', '.woff2': 'font/woff2', '.woff': 'font/woff', '.txt': 'text/plain; charset=utf-8',
};
const files = {};
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (f !== '_headers' && f !== '_redirects') files['/' + relative(root, p)] = { type: TYPES[extname(f)] ?? 'application/octet-stream', b64: readFileSync(p).toString('base64') };
  }
};
walk(root);
writeFileSync(new URL('../src/worker/assets.gen.ts', import.meta.url), `// Generated by scripts/bundle-assets.mjs: do not edit.\nexport const FILES: Record<string, { type: string; b64: string }> = ${JSON.stringify(files)};\n`);
console.log(`bundled ${Object.keys(files).length} files`);
